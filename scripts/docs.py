class HeadingSlugs:
    """Preserve Unicode letters/marks and GitHub-style collision suffixes."""

    def __init__(self) -> None:
        self.seen: set[str] = set()

    def slug(self, text: str) -> str:
        base = "".join(
            character for character in text.lower()
            if character in " -_" or unicodedata.category(character)[0] in "LMN"
        ).replace(" ", "-")
        candidate = base
        suffix = 0
        while candidate in self.seen:
            suffix += 1
            candidate = f"{base}-{suffix}"
        self.seen.add(candidate)
        return candidate


def load_json(path: Path) -> dict[str, Any]:
    def unique_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"{path}: duplicate JSON key {key!r}")
            result[key] = value
        return result

    value = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_keys)
    if not isinstance(value, dict):
        raise ValueError(f"{path}: expected a JSON object")
    return value


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=path.parent, prefix=f".{path.name}.", delete=False) as stream:
            temporary = Path(stream.name)
            json.dump(value, stream, indent=2, ensure_ascii=True)
            stream.write("\n")
        temporary.chmod(path.stat().st_mode & 0o777 if path.exists() else 0o644)
        temporary.replace(path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def repository_files(root: Path) -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=root, capture_output=True, check=True,
    )
    return sorted({
        path for path in result.stdout.decode("utf-8").split("\0")
        if path and (root / path).is_file()
    })


def text_content(token: Any) -> str:
    return "".join(
        child.content for child in token.children or []
        if child.type in {"text", "code_inline", "image"}
    )


class HTMLContent(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.anchors: set[str] = set()
        self.text: list[str] = []
        self.title: list[str] = []
        self.ignored: list[str] = []
        self.in_title = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = dict(attrs)
        for key in ("id", "name") if tag == "a" else ("id",):
            if attributes.get(key):
                self.anchors.add(attributes[key] or "")
        if tag in {"script", "style", "nav", "header", "footer", "noscript"}:
            self.ignored.append(tag)
        if tag == "title":
            self.in_title = True

    def handle_endtag(self, tag: str) -> None:
        if self.ignored and tag == self.ignored[-1]:
            self.ignored.pop()
        if tag == "title":
            self.in_title = False

    def handle_data(self, data: str) -> None:
        if not self.ignored:
            self.text.append(data)
        if self.in_title:
            self.title.append(data)


def analyze_markdown(content: str) -> dict[str, Any]:
    tokens = PARSER.parse(content)
    lines = content.splitlines()
    slugger = HeadingSlugs()
    anchors: set[str] = set()
    links: list[dict[str, Any]] = []
    sources: list[str] = []
    problems: list[tuple[int, str]] = []
    headings: list[tuple[int, str]] = []
    source_heading_level: int | None = None
    literal_lines: set[int] = set()

    for index, token in enumerate(tokens):
        if token.type in {"fence", "code_block"} and token.map:
            literal_lines.update(range(*token.map))
            if token.type == "fence":
                last = re.sub(r"^\s*(?:>\s*)*", "", lines[token.map[1] - 1]).strip()
                closing = re.fullmatch(
                    re.escape(token.markup[0]) + "{" + str(len(token.markup)) + r",}\s*", last,
                )
                if not closing:
                    problems.append((token.map[0] + 1, "unclosed fenced code block"))
        if token.type == "heading_open":
            inline = tokens[index + 1]
            title = text_content(inline)
            level = int(token.tag[1:])
            headings.append((level, title))
            anchors.add(slugger.slug(title))
            if source_heading_level is not None and level <= source_heading_level:
                source_heading_level = None
            if title.lower() in {"source", "sources", "references", "primary sources", "primary source"}:
                source_heading_level = level
        if token.type in {"html_block", "html_inline"}:
            html = HTMLContent()
            html.feed(token.content)
            anchors.update(html.anchors)
        if token.type != "inline":
            continue
        children = token.children or []
        source_line = re.match(r"^Sources?\s*:", text_content(token), flags=re.IGNORECASE)
        line_number = token.map[0] + 1 if token.map else 1
        for child_index, child in enumerate(children):
            if child.type == "html_inline":
                html = HTMLContent()
                html.feed(child.content)
                anchors.update(html.anchors)
            if child.type in {"strong_open", "link_open"} and child_index:
                previous = children[child_index - 1]
                if previous.type == "text" and re.search(r"\S-\s*$", previous.content):
                    problems.append((line_number, "joined list items; put the next item on a new line"))
            if child.type not in {"link_open", "image"}:
                continue
            href = child.attrGet("href" if child.type == "link_open" else "src")
            if not href:
                continue
            links.append({"url": href, "line": line_number})
            if (source_line or source_heading_level is not None) and urlsplit(href).scheme in {"http", "https"}:
                sources.append(href)
        if token.content.lstrip().startswith("|") and "\n" in token.content:
            rows = token.content.splitlines()
            if len(rows) > 1 and all(row.strip().startswith("|") for row in rows):
                problems.append((line_number, "table-like text was not parsed as a Markdown table"))

    for number, line in enumerate(lines):
        if number not in literal_lines and re.match(r"^#{1,6}[^#\s]", line):
            problems.append((number + 1, "heading marker needs a following space"))
        if number not in literal_lines and re.match(r"^\*(?:SDK|Design) baseline:", line):
            problems.append((number + 1, "generic generation baseline; use scoped sources and metadata"))
    if not headings or headings[0][0] != 1:
        problems.append((1, "document needs a leading level-one title"))
    if sum(level == 1 for level, _ in headings) > 1:
        problems.append((1, "multiple level-one document titles"))
    return {
        "anchors": anchors, "links": links, "sources": sorted(set(sources)),
        "problems": sorted(set(problems)), "headings": headings,
        "words": len(content.split()),
    }


def valid_date(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    try:
        return date.fromisoformat(value).isoformat() == value
    except ValueError:
        return False


def relative_document_path(value: Any) -> bool:
    return (
        isinstance(value, str) and bool(value) and not Path(value).is_absolute()
        and ".." not in Path(value).parts and "\\" not in value
    )


def http_url(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    parsed = urlsplit(value)
    return parsed.scheme in {"http", "https"} and bool(parsed.netloc)


def validate_metadata(root: Path, catalog: dict[str, Any]) -> list[str]:
    problems: list[str] = []
    if catalog.get("schema_version") != 1 or not valid_date(catalog.get("as_of")):
        problems.append("catalog: expected schema_version 1 and an ISO as_of date")
    if not isinstance(catalog.get("owners"), dict) or not catalog["owners"]:
        raise ValueError("catalog: a nonempty owner dictionary is required")
    for field in ("documents", "coverage"):
        if not isinstance(catalog.get(field), list):
            raise ValueError(f"catalog: required {field} array is missing or invalid")
    owners = catalog["owners"]
    documents = catalog["documents"]
    seen_paths: set[str] = set()
    seen_ids: set[str] = set()
    canonical: dict[str, str] = {}
    for document in documents:
        path = document.get("path")
        if not relative_document_path(path):
            problems.append(f"catalog: invalid document path {path!r}")
            continue
        if path in seen_paths or document.get("id") in seen_ids:
            problems.append(f"{path}: duplicate document path or ID")
        seen_paths.add(path)
        if not isinstance(document.get("id"), str) or not document["id"]:
            problems.append(f"{path}: missing stable document ID")
        else:
            seen_ids.add(document["id"])
        if document.get("owner") not in owners:
            problems.append(f"{path}: unknown or missing primary owner")
        if document.get("kind") not in KINDS:
            problems.append(f"{path}: unknown document kind")
        if document.get("release_status") not in RELEASE_STATUSES:
            problems.append(f"{path}: explicit release-status tag is required")
        if not (root / path).is_file():
            problems.append(f"{path}: registered document does not exist")
        if not isinstance(document.get("title"), str) or not document["title"].strip():
            problems.append(f"{path}: nonempty title is required")
        platforms = document.get("platforms", [])
        if not isinstance(platforms, list) or any(platform not in PLATFORMS for platform in platforms):
            problems.append(f"{path}: platform tags must use the declared platform names")
        review = document.get("review", {})
        if review.get("scope") not in REVIEW_SCOPES or not valid_date(review.get("checked_on")):
            problems.append(f"{path}: explicit review scope and date are required")
        elif review["checked_on"] > catalog["as_of"]:
            problems.append(f"{path}: review date exceeds catalog cutoff")
        sources = document.get("sources")
        if not isinstance(sources, list) or any(not http_url(url) for url in sources):
            problems.append(f"{path}: sources must be a list of absolute HTTP(S) URLs")
            sources = []
        if not sources and document.get("kind") not in SOURCE_OPTIONAL and "alias_of" not in document:
            problems.append(f"{path}: missing metadata source")
        if path.startswith("documentation/") and sources and "alias_of" not in document:
            first_source = sources[0].rstrip("/").lower()
            if first_source in canonical:
                problems.append(f"{path}: duplicate canonical topic with {canonical[first_source]}; declare an alias")
            else:
                canonical[first_source] = path
    for document in documents:
        if "alias_of" in document and document["alias_of"] not in seen_paths:
            problems.append(f"{document['path']}: alias target is not registered")
    by_path = {document["path"]: document for document in documents}
    for document in documents:
        visited: set[str] = set()
        target = document
        while target.get("alias_of") in by_path:
            if target["path"] in visited:
                problems.append(f"{document['path']}: alias cycle")
                break
            visited.add(target["path"])
            target = by_path[target["alias_of"]]
    coverage_keys: set[tuple[str, str]] = set()
    for entry in catalog.get("coverage", []):
        key = (entry.get("scope"), entry.get("source"))
        if key in coverage_keys:
            problems.append(f"coverage: duplicate catalog topic {key}")
        coverage_keys.add(key)
        if key[0] not in {"technology", "hig"} or not http_url(key[1]):
            problems.append(f"coverage: invalid scope/source {key}")
        if entry.get("disposition") not in COVERAGE_DISPOSITIONS:
            problems.append(f"coverage: unresolved disposition for {entry.get('title')}")
        if entry.get("disposition") == "excluded":
            if not entry.get("reason"):
                problems.append(f"coverage: exclusion needs a reason for {entry.get('title')}")
            continue
        paths = entry.get("paths", [])
        if not paths:
            problems.append(f"coverage: missing local mapping for {entry.get('title')}")
        for path in paths:
            if not relative_document_path(path) or not (root / path).exists():
                problems.append(f"coverage: missing target {path}")
            elif path.endswith(".md") and path not in seen_paths:
                problems.append(f"coverage: unregistered target {path}")

    def collection(filename: str, field: str) -> dict[str, Any]:
        data = load_json(root / "metadata" / filename)
        if data.get("schema_version") != 1 or not valid_date(data.get("as_of")):
            raise ValueError(f"{filename}: schema_version 1 and an ISO as_of date are required")
        if not isinstance(data.get(field), list):
            raise ValueError(f"{filename}: required {field} array is missing or invalid")
        if data["as_of"] != catalog["as_of"]:
            problems.append(f"{filename}: snapshot cutoff differs from catalog")
        return data

    releases = collection("releases.json", "releases")
    seen_releases: set[tuple[str, str]] = set()
    for release in releases.get("releases", []):
        key = (release.get("product"), release.get("status"))
        if not isinstance(key[0], str) or not key[0].strip():
            problems.append("releases: nonempty product name is required")
        if key in seen_releases:
            problems.append(f"releases: conflicting current entries for {key}")
        seen_releases.add(key)
        if key[1] not in {"shipping", "beta", "rc"} or not release.get("version"):
            problems.append(f"releases: invalid status/version for {key}")
        for field in ("released_on", "checked_on"):
            if release.get(field) is not None and not valid_date(release[field]):
                problems.append(f"releases: invalid {field} for {key}")
            elif release.get(field) and release[field] > releases.get("as_of", ""):
                problems.append(f"releases: {field} after cutoff for {key}")
        if not http_url(release.get("source")):
            problems.append(f"releases: missing primary source for {key}")
        if not valid_date(release.get("checked_on")):
            problems.append(f"releases: checked_on is required for {key}")
        elif valid_date(release.get("released_on")) and release["checked_on"] < release["released_on"]:
            problems.append(f"releases: release was not published by the review date for {key}")

    claims = collection("claims.json", "claims")
    claim_ids: set[str] = set()
    for claim in claims.get("claims", []):
        if claim.get("id") in claim_ids or not claim.get("id"):
            problems.append("claims: missing or duplicate ID")
        claim_ids.add(claim.get("id", ""))
        if claim.get("status") not in {"verified", "announcement-only", "unverified", "superseded", "retained-legacy"}:
            problems.append(f"claims: invalid evidence status for {claim.get('id')}")
        if not http_url(claim.get("source")) or not claim.get("locator"):
            problems.append(f"claims: source and locator required for {claim.get('id')}")
        elif claim.get("status") == "verified" and urlsplit(claim["source"]).path.rstrip("/") == "/documentation":
            problems.append(f"claims: documentation homepage cannot verify {claim.get('id')}")
        if not valid_date(claim.get("checked_on")):
            problems.append(f"claims: invalid checked_on for {claim.get('id')}")
        elif claim["checked_on"] > claims["as_of"]:
            problems.append(f"claims: review after cutoff for {claim.get('id')}")
        for field in ("source_published_on", "source_updated_on"):
            value = claim.get(field)
            if value is not None and not valid_date(value):
                problems.append(f"claims: invalid {field} for {claim.get('id')}")
            elif valid_date(value) and valid_date(claim.get("checked_on")) and value > claim["checked_on"]:
                problems.append(f"claims: {field} after review for {claim.get('id')}")
        for path in claim.get("affected_paths", []):
            if path not in seen_paths:
                problems.append(f"claims: unregistered affected path {path}")

    assets = collection("assets.json", "assets")
    asset_paths: set[str] = set()
    for asset in assets.get("assets", []):
        path = asset.get("path")
        if not relative_document_path(path) or path in asset_paths:
            problems.append(f"assets: invalid or duplicate path {path!r}")
            continue
        asset_paths.add(path)
        if asset.get("owner") not in {"D", "G"}:
            problems.append(f"{path}: design or sample asset ownership is required")
        if asset.get("rights_status") not in {"unverified", "licensed", "excluded", "original"}:
            problems.append(f"{path}: invalid rights status")
        if asset.get("rights_status") == "licensed" and not asset.get("license_source"):
            problems.append(f"{path}: a licensed asset needs its license source")
        if not (root / path).is_file():
            problems.append(f"{path}: missing registered asset")
        elif hashlib.sha256((root / path).read_bytes()).hexdigest() != asset.get("sha256"):
            problems.append(f"{path}: asset content changed; review provenance before updating its hash")
    snapshots = catalog.get("source_snapshots", [])
    if not isinstance(snapshots, list):
        raise ValueError("catalog: source_snapshots must be an array")
    snapshot_urls: set[str] = set()
    for snapshot in snapshots:
        url = snapshot.get("url")
        if not http_url(url) or url in snapshot_urls:
            problems.append(f"catalog: invalid or duplicate source snapshot {url!r}")
            continue
        snapshot_urls.add(url)
        if not valid_date(snapshot.get("retrieved_on")):
            problems.append(f"catalog: invalid source retrieval date for {url}")
        for field in ("sha256", "comparison_sha256"):
            if (field == "sha256" or field in snapshot) and not re.fullmatch(r"[a-f0-9]{64}", str(snapshot.get(field, ""))):
                problems.append(f"catalog: invalid {field} for {url}")
        if snapshot.get("comparison_method") not in {None, "apple-symbol-script-cache-buster-v1"}:
            problems.append(f"catalog: unknown comparison normalization for {url}")
        for field in ("source_published_on", "human_verified_on"):
            if snapshot.get(field) is not None and not valid_date(snapshot[field]):
                problems.append(f"catalog: invalid {field} for {url}")
    for path in repository_files(root):
        if path.endswith(".md") and path not in seen_paths:
            problems.append(f"{path}: Markdown document has no catalog entry")
        if path.startswith(("figma/", "os26-liquid-glass-example/")) and Path(path).suffix.lower() in ASSET_SUFFIXES and path not in asset_paths:
            problems.append(f"{path}: asset has no provenance record")
    return problems


def check_documents(root: Path, catalog: dict[str, Any]) -> list[str]:
    problems: list[str] = []
    analyzed: dict[str, dict[str, Any]] = {}
    actual_paths = set(repository_files(root))
    actual_directories = {parent.as_posix() for path in actual_paths for parent in Path(path).parents}
    for document in catalog["documents"]:
        path = document["path"]
        if not (root / path).is_file():
            continue
        parsed = analyze_markdown((root / path).read_text(encoding="utf-8"))
        analyzed[path] = parsed
        problems.extend(f"{path}:{line}: {message}" for line, message in parsed["problems"])
        if document["kind"] not in SOURCE_OPTIONAL and "alias_of" not in document and not parsed["sources"]:
            problems.append(f"{path}: missing rendered Source footer or Sources section")
    for path, parsed in list(analyzed.items()):
        for link in parsed["links"]:
            parsed_url = urlsplit(link["url"])
            if parsed_url.scheme or parsed_url.netloc:
                continue
            target_path = unquote(parsed_url.path)
            target = (root / path).parent / target_path if target_path else root / path
            if target_path.startswith("/"):
                problems.append(f"{path}:{link['line']}: root-relative link is not portable: {link['url']}")
                continue
            target = target.resolve()
            try:
                relative = target.relative_to(root.resolve()).as_posix()
            except ValueError:
                problems.append(f"{path}:{link['line']}: link escapes the repository: {link['url']}")
                continue
            if not target.exists():
                problems.append(f"{path}:{link['line']}: missing local target: {link['url']}")
                continue
            if (
                target.is_file() and relative not in actual_paths
                or target.is_dir() and relative not in actual_directories
            ):
                problems.append(f"{path}:{link['line']}: target is not publishable or uses incorrect case: {link['url']}")
                continue
            if target.is_dir() and (target / "README.md").exists():
                relative = (Path(relative) / "README.md").as_posix()
                target = target / "README.md"
            if parsed_url.fragment and target.suffix.lower() == ".md":
                if relative not in analyzed:
                    analyzed[relative] = analyze_markdown(target.read_text(encoding="utf-8"))
                fragment = unquote(parsed_url.fragment)
                if fragment not in analyzed[relative]["anchors"]:
                    problems.append(f"{path}:{link['line']}: missing anchor: {link['url']}")
    return problems


def check_accuracy(root: Path, catalog: dict[str, Any]) -> list[str]:
    """Check review coverage and staleness, not the truth of an attestation."""
    audit = load_json(root / "metadata/accuracy.json")
    if audit.get("schema_version") != 1 or not isinstance(audit.get("pages"), list):
        raise ValueError("accuracy.json: schema_version 1 and a pages array are required")
    problems: list[str] = []
    if audit.get("as_of") != catalog["as_of"]:
        problems.append("accuracy.json: snapshot cutoff differs from catalog")
    if audit.get("complete") is not True:
        problems.append("accuracy.json: full-body audit is incomplete")
    if not isinstance(audit.get("method"), str) or not audit["method"].strip():
        problems.append("accuracy.json: review method is required")
    try:
        recorded_at = datetime.fromisoformat(audit.get("recorded_at", ""))
        if recorded_at.tzinfo is None:
            raise ValueError("timezone required")
    except (TypeError, ValueError):
        problems.append("accuracy.json: recorded_at needs an ISO timestamp with timezone")

    def string_list(value: Any) -> bool:
        return isinstance(value, list) and all(isinstance(item, str) and item.strip() for item in value)

    if not string_list(audit.get("limitations")):
        problems.append("accuracy.json: limitations must be an explicit string array")
    expected = {document["path"] for document in catalog["documents"]}
    seen: set[str] = set()
    for page in audit["pages"]:
        if not isinstance(page, dict):
            problems.append("accuracy.json: each page review must be an object")
            continue
        path = page.get("path")
        if not isinstance(path, str) or path not in expected:
            problems.append(f"accuracy.json: unregistered reviewed path {path!r}")
            continue
        if path in seen:
            problems.append(f"{path}: duplicate full-body review")
        seen.add(path)
        if not valid_date(page.get("as_of")) or page["as_of"] > catalog["as_of"]:
            problems.append(f"{path}: review needs its own ISO cutoff no later than the catalog cutoff")
        if page.get("full_body_reviewed") is not True or page.get("status") not in {
            "verified", "corrected", "verified-qualified",
        }:
            problems.append(f"{path}: full-body review is not complete")
        if page.get("remaining_blockers") != []:
            problems.append(f"{path}: an explicit empty remaining_blockers array is required")
        if not string_list(page.get("qualifications")):
            problems.append(f"{path}: review qualifications must be an explicit string array")
        elif page.get("status") == "verified-qualified" and not page["qualifications"]:
            problems.append(f"{path}: qualified review needs its specific qualifications")
        local = (root / path).resolve()
        if not local.is_relative_to(root.resolve()) or not local.is_file():
            problems.append(f"{path}: reviewed file is missing or outside the repository")
            continue
        content = local.read_bytes()
        if hashlib.sha256(content).hexdigest() != page.get("content_sha256"):
            problems.append(f"{path}: content changed since full-body review")
        tokens = PARSER.parse(content.decode("utf-8"))
        headings = [
            text_content(tokens[index + 1])
            for index, token in enumerate(tokens) if token.type == "heading_open"
        ]
        if page.get("headings_reviewed") != headings:
            problems.append(f"{path}: review does not account for every current heading")
        examples = page.get("code_examples")
        fences = sum(token.type == "fence" for token in tokens)
        if not isinstance(examples, dict):
            problems.append(f"{path}: code-example review scope is required")
        elif (
            type(examples.get("fences_reviewed")) is not int
            or examples["fences_reviewed"] != fences
            or not isinstance(examples.get("verification"), str)
            or not examples["verification"].strip()
        ):
            problems.append(f"{path}: code-example review must account for all fences and state actual verification")
        sources = page.get("sources")
        if not isinstance(sources, list) or not sources:
            problems.append(f"{path}: full-body review needs primary or repository evidence")
            continue
        for source in sources:
            if not isinstance(source, dict):
                problems.append(f"{path}: review evidence must be an object")
                continue
            if not re.fullmatch(r"[a-f0-9]{64}", str(source.get("sha256", ""))):
                problems.append(f"{path}: review evidence needs a valid raw sha256")
            if not isinstance(source.get("locator"), str) or not source["locator"].strip():
                problems.append(f"{path}: review evidence needs a precise locator")
            if ("url" in source) == ("path" in source):
                problems.append(f"{path}: evidence needs exactly one primary URL or repository path")
            elif "url" in source:
                if not http_url(source["url"]) or not http_url(source.get("retrieval_url")):
                    problems.append(f"{path}: evidence needs canonical and retrieval HTTP(S) URLs")
            elif not relative_document_path(source["path"]):
                problems.append(f"{path}: invalid repository-evidence path")
            else:
                evidence = (root / source["path"]).resolve()
                if not evidence.is_relative_to(root.resolve()) or not evidence.is_file():
                    problems.append(f"{path}: repository evidence is missing or outside the repository")
                elif hashlib.sha256(evidence.read_bytes()).hexdigest() != source.get("sha256"):
                    problems.append(f"{path}: repository evidence changed since full-body review: {source['path']}")
    for path in sorted(expected - seen):
        problems.append(f"{path}: missing full-body review")
    return problems


def table_cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def link_to(index_path: str, target: str) -> str:
    return quote(os.path.relpath(target, Path(index_path).parent), safe="/.-_")


def index_table(index_path: str, documents: list[dict[str, Any]]) -> list[str]:
    result = [
        "| Topic | Kind | Platforms tagged in page | Release status | Initial review scope |",
        "|---|---|---|---|---|",
    ]
    for document in sorted(documents, key=lambda item: item["title"].casefold()):
        label = table_cell(document["title"])
        path = link_to(index_path, document["path"])
        platforms = ", ".join(document.get("platforms", [])) or "Not indexed"
        review = document["review"]["scope"]
        if "alias_of" in document:
            review = f"Alias of `{document['alias_of']}`"
        result.append(f"| [{label}]({path}) | {document['kind']} | {platforms} | {document['release_status']} | {review} |")
    return result


def generated_indexes(catalog: dict[str, Any]) -> dict[str, str]:
    documents = [document for document in catalog["documents"] if document["kind"] != "index"]
    outputs: dict[str, str] = {}
    groups = {
        "documentation/README.md": ("Reference index", "documentation/"),
        "human-interface-guidelines/README.md": ("Human Interface Guidelines index", "human-interface-guidelines/"),
        "guides/README.md": ("Migration and readiness guides", "guides/"),
    }
    for category in ("getting-started", "foundations", "patterns", "components", "inputs", "technologies"):
        groups[f"human-interface-guidelines/{category}/README.md"] = (
            category.replace("-", " ").capitalize(), f"human-interface-guidelines/{category}/",
        )
    for path, (title, prefix) in groups.items():
        rows = [
            f"# {title}", "", GENERATED_NOTICE, "",
            f"Catalog snapshot: {human_date(catalog['as_of'])}.",
            "",
            "The review column preserves the initial catalog/changed-content pass.",
            "`metadata/accuracy.json` separately records full-body outcomes for exact page hashes.",
            "`catalog-only` verifies the topic mapping, not every statement. Platform tags are",
            "navigation aids extracted from the page, not symbol-level availability guarantees.",
            "`mixed` spans shipping and beta material; `independent` is not tied to one OS release.",
            "`not-assessed` preserves uncertainty rather than silently claiming a shipping status.",
            "See [contributor guidance](" + link_to(path, "CONTRIBUTING.md") + ").",
            "",
        ]
        selected = [document for document in documents if document["path"].startswith(prefix)]
        if path == "documentation/README.md":
            for owner, owner_title in catalog["owners"].items():
                subset = [document for document in selected if document["owner"] == owner]
                if subset:
                    rows.extend([f"## {owner_title}", ""] + index_table(path, subset) + [""])
        else:
            if path == "human-interface-guidelines/README.md":
                for category in ("getting-started", "foundations", "patterns", "components", "inputs", "technologies"):
                    rows.append(f"- [{category.replace('-', ' ').capitalize()}]({category}/README.md)")
                rows.append("")
            rows.extend(index_table(path, selected))
            rows.append("")
        outputs[path] = "\n".join(rows).rstrip() + "\n"
    return outputs


def human_date(value: str | None) -> str:
    if value is None:
        return "Not recorded"
    parsed = date.fromisoformat(value)
    return f"{parsed:%B} {parsed.day}, {parsed.year}"


def baseline_section(root: Path, catalog: dict[str, Any]) -> str:
    releases = load_json(root / "metadata/releases.json")
    lines = [
        f"**Research cutoff: {human_date(releases['as_of'])}.** This is a dated snapshot, not a live latest-version service.",
        "",
        "| Product | Version | Status | Release date |",
        "|---|---|---|---|",
    ]
    for release in releases["releases"]:
        build = f" (`{release['build']}`)" if release.get("build") else ""
        lines.append(
            f"| {release['product']} | {release['version']}{build} | {release['status']} | "
            f"[{human_date(release.get('released_on'))}]({release['source']}) |"
        )
    counts = Counter(
        document["path"].split("/")[0] for document in catalog["documents"]
        if document["kind"] != "index"
    )
    scoped = Counter(entry["scope"] for entry in catalog["coverage"])
    resolved = Counter(
        entry["scope"] for entry in catalog["coverage"]
        if entry["disposition"] in COVERAGE_DISPOSITIONS
        and (entry["disposition"] == "excluded" or all((root / path).exists() for path in entry["paths"]))
    )
    assets = load_json(root / "metadata/assets.json")
    figma_count = sum(asset["path"].startswith("figma/") for asset in assets["assets"])
    lines.extend([
        "",
        f"**Catalog scope:** {resolved['technology']}/{scoped['technology']} technology entries and "
        f"{resolved['hig']}/{scoped['hig']} indexed HIG articles have an explicit local disposition.",
        f"The repository has {counts['documentation']} reference pages (including aliases), "
        f"{counts['human-interface-guidelines']} HIG articles (including retained legacy material), "
        f"and {figma_count} cataloged Figma-directory images. Generated indexes are excluded from page counts.",
        "Coverage is not a certification of every API symbol or every sentence.",
    ])
    return "\n".join(lines)


def generated_readme(root: Path, catalog: dict[str, Any]) -> str:
    content = (root / "README.md").read_text(encoding="utf-8")
    if content.count(README_START) != 1 or content.count(README_END) != 1:
        raise ValueError("README.md needs exactly one generated baseline marker pair")
    before, remainder = content.split(README_START, 1)
    _, after = remainder.split(README_END, 1)
    return before + README_START + "\n\n" + baseline_section(root, catalog) + "\n\n" + README_END + after


def generate(root: Path, catalog: dict[str, Any], check: bool = False) -> list[str]:
    expected = generated_indexes(catalog)
    expected["README.md"] = generated_readme(root, catalog)
    problems: list[str] = []
    for path, content in expected.items():
        target = root / path
        if target.exists() and target.read_text(encoding="utf-8") == content:
            continue
        if check:
            problems.append(f"{path}: generated output is stale; run scripts/docs.py generate")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    return problems


def register(root: Path, catalog: dict[str, Any], args: argparse.Namespace) -> None:
    path = args.path
    if not relative_document_path(path) or not (root / path).is_file() or not path.endswith(".md"):
        raise ValueError("register expects an existing repository-relative Markdown file")
    if args.owner not in catalog["owners"]:
        raise ValueError(f"unknown owner: {args.owner}")
    if any(document["path"] == path for document in catalog["documents"]):
        raise ValueError(f"already registered: {path}; edit its metadata explicitly")
    parsed = analyze_markdown((root / path).read_text(encoding="utf-8"))
    catalog["documents"].append({
        "id": path.removesuffix(".md"), "path": path,
        "title": parsed["headings"][0][1] if parsed["headings"] else Path(path).stem,
        "kind": args.kind, "owner": args.owner,
        "release_status": "not-assessed",
        "sources": args.source or parsed["sources"],
        "review": {"scope": "catalog-only", "checked_on": catalog["as_of"]},
    })
    catalog["documents"].sort(key=lambda document: document["path"])
    write_json(root / "metadata/catalog.json", catalog)


