def source_candidates(url: str) -> list[str]:
    parsed = urlsplit(url)
    if parsed.netloc == "developer.apple.com" and parsed.path.startswith("/documentation/") and not parsed.path.endswith((".md", ".json")):
        stem = parsed.path.rstrip("/")
        return [
            urljoin(url, stem + ".md"),
            urljoin(url, "/tutorials/data" + stem + ".json"), url,
        ]
    if parsed.netloc == "developer.apple.com" and parsed.path.startswith("/design/human-interface-guidelines"):
        return [urljoin(url, "/tutorials/data" + parsed.path.rstrip("/") + ".json"), url]
    return [url]


def source_identity(body: bytes, content_type: str) -> tuple[str, bool]:
    if content_type.startswith(("image/", "audio/", "video/")) or "application/pdf" in content_type:
        return "", bool(body)
    text = body.decode("utf-8", errors="replace")
    if "json" in content_type:
        data = json.loads(text)
        if not isinstance(data, dict):
            raise ValueError("Expected a documentation JSON object, not a scalar or array")
        metadata = data.get("metadata", {})
        if not isinstance(metadata, dict):
            raise ValueError("Expected documentation JSON metadata to be an object")
        title = metadata.get("title", data.get("title", ""))
        if not isinstance(title, str):
            raise ValueError("Expected a documentation JSON title string")
        substantive = any(data.get(key) for key in ("abstract", "primaryContentSections", "topicSections", "sections"))
        return title, substantive
    if "html" in content_type:
        html = HTMLContent()
        html.feed(text)
        visible = " ".join(html.text)
        shell = "This page requires JavaScript" in visible or len(visible.split()) < 40
        return " ".join(html.title).strip(), not shell
    tokens = PARSER.parse(text)
    title = ""
    body_words = 0
    declaration = False
    for index, token in enumerate(tokens):
        if token.type == "heading_open" and token.tag == "h1" and not title:
            title = text_content(tokens[index + 1])
        if token.type in {"fence", "code_block"} and token.content.strip():
            declaration = True
        if token.type == "inline" and (index == 0 or tokens[index - 1].type != "heading_open"):
            rendered = text_content(token)
            if "Copyright" in rendered and "Apple Inc." in rendered:
                continue
            body_words += len(rendered.split())
    return title, bool(title and (body_words >= 5 or declaration))


def comparison_hash(body: bytes, content_type: str) -> str:
    if "html" in content_type:
        # Apple's per-request symbol-script cache token changes without a page revision.
        body = re.sub(
            rb'(<script\b[^>]*\bsrc=["\']https://sfss\.cdn-apple\.com/[^"\'?]+/sf-symbol\.js)\?\d+(["\'])',
            rb"\1\2", body,
        )
    return hashlib.sha256(body).hexdigest()


def technology_entries(data: dict[str, Any]) -> dict[str, dict[str, str]]:
    if not data.get("sections") or not isinstance(data.get("references"), dict):
        raise ValueError("technology catalog has an unexpected structure")
    entries: dict[str, dict[str, str]] = {}
    for section in data["sections"]:
        for group in section.get("groups", []):
            for technology in group.get("technologies", []):
                identifier = technology["destination"]["identifier"]
                reference = data["references"][identifier]
                url = urljoin("https://developer.apple.com", reference["url"])
                entries[url] = {"title": technology["title"], "group": group["name"]}
    if not entries:
        raise ValueError("technology catalog contains no technology entries")
    return entries


def hig_entries(
    fetch: Callable[[str], dict[str, Any]],
) -> tuple[dict[str, dict[str, str]], list[str], list[dict[str, str]]]:
    pending = [HIG_CATALOG]
    visited: set[str] = set()
    entries: dict[str, dict[str, str]] = {}
    failures: list[dict[str, str]] = []
    while pending:
        url = pending.pop(0)
        if url in visited:
            continue
        visited.add(url)
        try:
            data = fetch(url)
            if "topicSections" not in data or not isinstance(data.get("references"), dict):
                raise ValueError("HIG group has an unexpected structure")
            for section in data["topicSections"]:
                for identifier in section.get("identifiers", []):
                    reference = data["references"][identifier]
                    target = urljoin("https://developer.apple.com", reference["url"])
                    if reference.get("role") == "collectionGroup":
                        target_parts = urlsplit(target)
                        if target_parts.netloc != "developer.apple.com" or not target_parts.path.startswith("/design/human-interface-guidelines/"):
                            raise ValueError(f"unexpected HIG group destination: {target}")
                        pending.append(urljoin(target, "/tutorials/data" + target_parts.path + ".json"))
                    elif reference.get("kind") == "article":
                        entries[target] = {"title": reference["title"]}
        except (OSError, ValueError, KeyError, TypeError) as error:
            failures.append({"url": url, "error": str(error)})
    return entries, sorted(visited), failures


def fetch_catalog_json(url: str) -> dict[str, Any]:
    for attempt in range(3):
        try:
            request = Request(url, headers={"User-Agent": "apple-os-documentation-catalog-check/1.0"})
            with urlopen(request, timeout=25) as response:
                body = response.read(4 * 1024 * 1024 + 1)
            if len(body) > 4 * 1024 * 1024:
                raise ValueError(f"catalog exceeds the 4 MiB response limit: {url}")
            data = json.loads(body)
            if not isinstance(data, dict):
                raise ValueError(f"expected a catalog object: {url}")
            return data
        except HTTPError as error:
            if error.code not in {429, 500, 502, 503, 504} or attempt == 2:
                raise
            time.sleep(2 ** (attempt + 1))
        except (URLError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(2 ** (attempt + 1))
    raise RuntimeError("catalog retry loop exhausted")


def compare_catalogs(root: Path, catalog: dict[str, Any], args: argparse.Namespace) -> int:
    def fetch(url: str) -> dict[str, Any]:
        if args.snapshot_dir:
            name = Path(urlsplit(url).path).stem
            filename = (
                "apple-technologies.json" if url == TECHNOLOGY_CATALOG
                else "apple-hig.json" if url == HIG_CATALOG
                else f"apple-hig-{name}.json"
            )
            return load_json(args.snapshot_dir / filename)
        return fetch_catalog_json(url)

    failures: list[dict[str, str]] = []
    live: dict[str, dict[str, dict[str, str]]] = {}
    try:
        live["technology"] = technology_entries(fetch(TECHNOLOGY_CATALOG))
    except (OSError, ValueError, KeyError, TypeError) as error:
        failures.append({"url": TECHNOLOGY_CATALOG, "error": str(error)})
    live["hig"], visited, hig_failures = hig_entries(fetch)
    failures.extend(hig_failures)
    current = {
        scope: {entry["source"]: entry for entry in catalog["coverage"] if entry["scope"] == scope}
        for scope in ("technology", "hig")
    }
    changes: list[dict[str, Any]] = []
    if not failures:
        by_path = {document["path"]: document["owner"] for document in catalog["documents"]}
        for scope, entries in live.items():
            for url in sorted(entries.keys() - current[scope].keys()):
                changes.append({
                    "scope": scope, "status": "new", "url": url, **entries[url],
                    "owner": "D" if scope == "hig" else None,
                    "action": "Assign an owner and verify a dedicated page or explicit disposition.",
                })
            for url in sorted(current[scope].keys() - entries.keys()):
                old = current[scope][url]
                changes.append({
                    "scope": scope, "status": "unindexed", "url": url,
                    "title": old["title"], "paths": old["paths"],
                    "owners": sorted({by_path[path] for path in old["paths"] if path in by_path}),
                    "action": "Review for move or retained legacy status; index absence is not deprecation.",
                })
            for url in sorted(entries.keys() & current[scope].keys()):
                if entries[url]["title"] != current[scope][url]["title"]:
                    changes.append({
                        "scope": scope, "status": "renamed", "url": url,
                        "previous_title": current[scope][url]["title"], "title": entries[url]["title"],
                        "paths": current[scope][url]["paths"],
                    })
    report = {
        "schema_version": 1, "checked_at": datetime.now(timezone.utc).isoformat(),
        "catalog_cutoff": catalog["as_of"],
        "input": "saved snapshots" if args.snapshot_dir else "live primary catalogs",
        "complete": not failures,
        "counts": {scope: len(entries) for scope, entries in live.items()},
        "hig_groups_visited": visited, "access_failures": failures, "changes": changes,
        "note": "No removal comparison is made after a partial traversal. Reports never rewrite source prose or review dates.",
    }
    write_json(args.output, report)
    print(f"Catalog comparison: {len(changes)} change(s), {len(failures)} access/structure failure(s). Report: {args.output}")
    return 1 if changes or failures else 0


def probe_source(url: str, expected_title: str | None = None) -> dict[str, Any]:
    attempts: list[dict[str, Any]] = []
    for candidate in source_candidates(url):
        for retry in range(3):
            try:
                request = Request(candidate, headers={"User-Agent": "apple-os-documentation-source-check/1.0"})
                with urlopen(request, timeout=25) as response:
                    body = response.read(4 * 1024 * 1024 + 1)
                    final_url = response.url
                    content_type = response.headers.get("Content-Type", "")
                    if len(body) > 4 * 1024 * 1024:
                        return {"url": url, "status": "too-large", "retrieval_url": candidate, "attempts": attempts}
                    title, substantive = source_identity(body, content_type)
                    status = "redirected" if final_url != candidate else "retrieved"
                    if not substantive:
                        status = "shell"
                    if expected_title and title and substantive:
                        normalized = re.sub(r"[^a-z0-9]", "", title.lower())
                        expected = re.sub(r"[^a-z0-9]", "", expected_title.lower())
                        if expected and expected not in normalized and normalized not in expected:
                            status = "title-mismatch"
                    attempts.append({"url": candidate, "status": status})
                    if status in {"shell", "title-mismatch"} and candidate != source_candidates(url)[-1]:
                        break
                    return {
                        "url": url, "status": status, "retrieval_url": candidate,
                        "final_url": final_url, "title": title,
                        "sha256": hashlib.sha256(body).hexdigest(), "bytes": len(body),
                        "comparison_sha256": comparison_hash(body, content_type),
                        "retrieved_on": datetime.now(timezone.utc).isoformat(),
                        "source_published_on": None, "human_verified_on": None,
                        "attempts": attempts,
                    }
            except HTTPError as error:
                if error.code in {429, 500, 502, 503, 504} and retry < 2:
                    delay = min(int(error.headers.get("Retry-After", "2")) if error.headers.get("Retry-After", "").isdigit() else 2 ** (retry + 1), 15)
                    time.sleep(delay)
                    continue
                status = "missing" if error.code == 404 else "rate-limited" if error.code == 429 else "inaccessible"
                attempts.append({"url": candidate, "status": status, "http_status": error.code})
                break
            except (URLError, TimeoutError, OSError, ValueError) as error:
                if retry < 2:
                    time.sleep(2 ** retry)
                    continue
                attempts.append({"url": candidate, "status": "inaccessible", "error": str(error)})
                break
    return {"url": url, "status": attempts[-1]["status"], "attempts": attempts}


def check_sources(root: Path, catalog: dict[str, Any], args: argparse.Namespace) -> int:
    snapshots = catalog.get("source_snapshots", [])
    baseline = {snapshot["url"]: snapshot for snapshot in snapshots}
    if args.catalogs_only:
        urls = list(baseline)
        titles: dict[str, str] = {}
    else:
        titles = {entry["source"]: entry["title"] for entry in catalog["coverage"]}
        urls = list(dict.fromkeys(list(baseline) + [
            url for document in catalog["documents"] for url in document["sources"]
        ]))
        if getattr(args, "include_body_links", False):
            body_links = [
                link["url"]
                for document in catalog["documents"] if (root / document["path"]).is_file()
                for link in analyze_markdown((root / document["path"]).read_text(encoding="utf-8"))["links"]
                if http_url(link["url"])
            ]
            urls = list(dict.fromkeys(urls + body_links))
    if args.url:
        urls = args.url
        titles = {}
    selected = urls[args.offset:args.offset + args.max_urls]
    if not selected:
        raise ValueError("no sources selected; check the offset, catalog snapshots, or explicit URLs")
    cache = load_json(args.output) if args.output.exists() else {"results": []}
    cached = {result["url"]: result for result in cache.get("results", []) if result.get("status") in {"retrieved", "redirected"}}
    now = datetime.now(timezone.utc)

    def retrieve(url: str) -> dict[str, Any]:
        previous = cached.get(url)
        comparison_available = (
            not baseline.get(url, {}).get("comparison_sha256")
            or bool(previous and previous.get("comparison_sha256"))
        )
        if previous and not args.refresh and comparison_available:
            retrieved = datetime.fromisoformat(previous["retrieved_on"])
            if (now - retrieved).total_seconds() < 86400:
                return {**previous, "cached": True}
        return probe_source(url, titles.get(url))

    with ThreadPoolExecutor(max_workers=3) as executor:
        results = list(executor.map(retrieve, selected))
    for result in results:
        original = baseline.get(result["url"])
        if original and result.get("sha256"):
            result["raw_changed"] = result["sha256"] != original["sha256"]
            if original.get("comparison_sha256"):
                result["upstream_changed"] = result.get("comparison_sha256") != original["comparison_sha256"]
            else:
                result["upstream_changed"] = result["raw_changed"]
    remaining = len(urls) - len(selected)
    report = {
        "schema_version": 1, "checked_at": now.isoformat(),
        "scope": "catalog snapshots" if args.catalogs_only else "primary sources and body links" if getattr(args, "include_body_links", False) else "selected primary sources",
        "eligible_sources": len(urls), "requested_sources": len(selected),
        "not_requested": remaining, "complete_for_selected_scope": remaining == 0,
        "note": "Retrieval and matching titles are not human factual verification. HTTP errors and shells remain unresolved. Raw hashes are retained; comparison hashes ignore only the numeric cache token on Apple's sf-symbol.js script URL.",
        "results": results,
    }
    write_json(args.output, report)
    failures = sum(result["status"] not in {"retrieved", "redirected"} for result in results)
    drift = sum(result.get("upstream_changed", False) for result in results)
    cache_only = sum(result.get("raw_changed", False) and not result.get("upstream_changed", False) for result in results)
    print(f"Sources: {len(results)} requested, {remaining} not requested, {failures} unresolved, {drift} changed, {cache_only} cache-token-only differences. Report: {args.output}")
    return 1 if failures or drift else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    subcommands = parser.add_subparsers(dest="command", required=True)
    check = subcommands.add_parser("check", help="Validate metadata, Markdown, review hashes, local links, assets and generated output")
    check.add_argument("--skip-generated", action="store_true", help="Diagnose content before regenerating indexes")
    subcommands.add_parser("generate", help="Regenerate indexes and the README baseline")
    inventory_parser = subcommands.add_parser("inventory", help="Count actual repository files and words")
    inventory_parser.add_argument("--output", type=Path)
    registration = subcommands.add_parser("register", help="Register a new page without marking its body verified")
    registration.add_argument("path")
    registration.add_argument("--owner", required=True)
    registration.add_argument("--kind", choices=sorted(KINDS), required=True)
    registration.add_argument("--source", action="append")
    sources = subcommands.add_parser("sources", help="Produce a bounded primary-source access/drift report")
    sources.add_argument("--output", type=Path, required=True)
    sources.add_argument("--max-urls", type=int, default=30)
    sources.add_argument("--offset", type=int, default=0)
    sources.add_argument("--catalogs-only", action="store_true")
    sources.add_argument("--include-body-links", action="store_true", help="Also consider external links in parsed Markdown")
    sources.add_argument("--url", action="append")
    sources.add_argument("--refresh", action="store_true")
    catalogs = subcommands.add_parser("catalogs", help="Compare technology and fully traversed HIG catalogs")
    catalogs.add_argument("--output", type=Path, required=True)
    catalogs.add_argument("--snapshot-dir", type=Path, help="Use a saved apple-technologies/apple-hig snapshot set")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        catalog = load_json(root / "metadata/catalog.json")
        if args.command == "check":
            problems = validate_metadata(root, catalog) + check_documents(root, catalog) + check_accuracy(root, catalog)
            if not args.skip_generated:
                problems += generate(root, catalog, check=True)
            for problem in problems:
                print(problem, file=sys.stderr)
            print(f"Documentation check: {len(problems)} problem(s), {len(catalog['documents'])} registered documents.")
            return 1 if problems else 0
        if args.command == "generate":
            generate(root, catalog)
            print("Generated reference/HIG/guide indexes and the README baseline.")
        elif args.command == "register":
            register(root, catalog, args)
            print(f"Registered {args.path} with catalog-only review scope.")
        elif args.command == "inventory":
            result = inventory(root, catalog)
            if args.output:
                write_json(args.output, result)
            else:
                print(json.dumps(result, indent=2))
        elif args.command == "sources":
            if args.max_urls < 1 or args.offset < 0:
                raise ValueError("max-urls must be positive and offset cannot be negative")
            return check_sources(root, catalog, args)
        elif args.command == "catalogs":
            return compare_catalogs(root, catalog, args)
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as error:
        print(f"Documentation maintenance failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
